/*
 * 写一个 DHT 段到缓冲区
 * DHT 段格式：
 *   标记(2字节=FF C4) + 长度(2字节) + 表ID(1字节) + 表数据(n字节)
 *   长度 = 3 + n（表ID 1字节 + 表数据 n字节，再加上长度字段自身的2字节）
 */
static void write_dht(unsigned char *buf, int *pos,
                      unsigned char table_id,
                      const unsigned char *data, int data_len)
{
    int seg_len = 3 + data_len;
    buf[(*pos)++] = 0xFF;
    buf[(*pos)++] = 0xC4;                         /* DHT 标记 */
    buf[(*pos)++] = (seg_len >> 8) & 0xFF;        /* 段长度 (大端) */
    buf[(*pos)++] = seg_len & 0xFF;
    buf[(*pos)++] = table_id;                     /* 表ID */
    memcpy(buf + *pos, data, data_len);           /* 拷贝表数据 */
    *pos += data_len;
}

unsigned char* jpeg_fix_huffman(const unsigned char *src,
                                 int src_len, int *out_len)
{
    /* 计算 4 张 Huffman 表需要的总字节数 */
    int dht_size = 0;
    dht_size += 4 + sizeof(huff_y_dc);    /* 每个 DHT: 4字节头 + 数据 */
    dht_size += 4 + sizeof(huff_y_ac);
    dht_size += 4 + sizeof(huff_uv_dc);
    dht_size += 4 + sizeof(huff_uv_ac);

    /*
     * 新缓冲区大小 = SOI(2) + 4张DHT表 + (原始长度 - 2)
     * 减 2 是因为跳过原始数据开头的 2 字节（可能不是 SOI 或格式不对）
     */
    int new_size = 2 + dht_size + (src_len - 2);
    unsigned char *dst = (unsigned char*)malloc(new_size);
    if (!dst) return NULL;

    int pos = 0;

    /* 1. 写入 SOI 标记 0xFFD8 */
    dst[pos++] = 0xFF;
    dst[pos++] = 0xD8;

    /*
     * 2. 依次写入 4 张 Huffman 表
     *    表ID 编码：高4位=类型(0=DC,1=AC)，低4位=通道(0=Y,1=UV)
     */
    write_dht(dst, &pos, 0x00, huff_y_dc,  sizeof(huff_y_dc));   /* Y-DC   */
    write_dht(dst, &pos, 0x10, huff_y_ac,  sizeof(huff_y_ac));   /* Y-AC   */
    write_dht(dst, &pos, 0x01, huff_uv_dc, sizeof(huff_uv_dc));  /* UV-DC  */
    write_dht(dst, &pos, 0x11, huff_uv_ac, sizeof(huff_uv_ac));  /* UV-AC  */

    /* 3. 拼接原始压缩数据（跳过开头 2 字节） */
    memcpy(dst + pos, src + 2, src_len - 2);
    pos += src_len - 2;

    *out_len = pos;
    return dst;
}
